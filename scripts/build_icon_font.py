#!/usr/bin/env python3
"""Builds the Studio Icons font and its C# glyph table from assets/icons.

Usage: `uv run python scripts/build_icon_font.py`.

`assets/icons/icons.json` pins every icon's code point; add an icon at the end
so that existing glyphs keep theirs. Adapted from contr-windows'
`scripts/build-icon-font.py`.
"""

from __future__ import annotations

import json
import pathlib
import re
from typing import Any, TYPE_CHECKING
from xml.etree import ElementTree  # nosec B405

from fontTools import fontBuilder
from fontTools.misc import timeTools
from fontTools.pens import cu2quPen
from fontTools.pens import transformPen
from fontTools.pens import ttGlyphPen
from fontTools.svgLib import path as svg_path

if TYPE_CHECKING:
    from fontTools.ttLib.tables import _g_l_y_f

UNITS_PER_EM = 2048
# A fixed date, so that the same SVGs build the same bytes.
BUILT = timeTools.timestampFromString("Sat Nov 07 00:00:00 2026")
SVG = "{http://www.w3.org/2000/svg}"
NAMESPACE = "DelphiModernizer.Studio.UI.Common.Icons"
ROOT = pathlib.Path(__file__).resolve().parent.parent
ICONS = ROOT / "assets" / "icons"
# The app ships the font; the shared UI library holds the glyph table that
# every module uses.
FONT = ROOT / "src" / "App" / "DelphiModernizer.Studio.App" / "Assets" / "Fonts"
TABLE = ROOT / "src" / "Shared" / "DelphiModernizer.Studio.UI.Common" / "Icons"


def _outline(svg_file: pathlib.Path) -> _g_l_y_f.Glyph:
    """Draws an icon's paths as a TrueType glyph.

    Args:
        svg_file: The icon, as Fluent UI System Icons draws it.

    Returns:
        The glyph, its view box scaled to the em and its y axis pointing up.

    Raises:
        ValueError: If the SVG has no view box or a path has no data.
    """
    # The SVGs are this repository's own assets, not untrusted XML.
    svg = ElementTree.parse(svg_file).getroot()  # nosec B314
    view_box = svg.get("viewBox")
    if view_box is None:
        raise ValueError(f"{svg_file} has no viewBox")
    _, _, width, height = (float(value) for value in view_box.split())
    scale = UNITS_PER_EM / max(width, height)
    pen = ttGlyphPen.TTGlyphPen(None)
    flipped = transformPen.TransformPen(
        cu2quPen.Cu2QuPen(pen, max_err=1.0, reverse_direction=True),
        (scale, 0, 0, -scale, 0, UNITS_PER_EM),
    )
    for path in svg.iter(f"{SVG}path"):
        data = path.get("d")
        if data is None:
            raise ValueError(f"{svg_file} has a path without data")
        # SVG lets a path draw on after Z from the closed subpath's start;
        # fontTools wants a move first.
        svg_path.parse_path(
            re.sub(r"([zZ])\s*(?=[^mMzZ\s])", r"\1m0 0", data), flipped
        )
    return pen.glyph()


def _build_font(manifest: dict[str, Any]) -> int:
    """Writes the font of every icon in the manifest.

    Args:
        manifest: The parsed `icons.json`.

    Returns:
        The number of glyphs in the font's character map.
    """
    glyph_order = [".notdef"]
    glyphs = {".notdef": ttGlyphPen.TTGlyphPen(None).glyph()}
    cmap: dict[int, str] = {}
    for icon in manifest["icons"]:
        name = icon["name"]
        glyph_order.append(name)
        glyphs[name] = _outline(ICONS / "svg" / f"{name}.svg")
        cmap[int(icon["codepoint"], 16)] = name

    builder = fontBuilder.FontBuilder(UNITS_PER_EM, isTTF=True)
    builder.setupGlyphOrder(glyph_order)
    builder.setupCharacterMap(cmap)
    builder.setupGlyf(glyphs)
    glyf = builder.font["glyf"]
    builder.setupHorizontalMetrics({
        name: (UNITS_PER_EM, getattr(glyf[name], "xMin", 0))
        for name in glyph_order
    })
    builder.setupHorizontalHeader(ascent=UNITS_PER_EM, descent=0)
    builder.setupNameTable({
        "familyName": manifest["family"],
        "styleName": "Regular",
        "copyright": (
            "Icons from Fluent UI System Icons, Copyright (c) 2020 Microsoft"
            " Corporation, MIT licence"
        ),
    })
    builder.setupOS2(
        sTypoAscender=UNITS_PER_EM,
        sTypoDescender=0,
        sTypoLineGap=0,
        usWinAscent=UNITS_PER_EM,
        usWinDescent=0,
        achVendID="DMZS",
    )
    builder.setupPost()
    builder.font.recalcTimestamp = False
    builder.font["head"].created = BUILT
    builder.font["head"].modified = BUILT
    FONT.mkdir(parents=True, exist_ok=True)
    builder.save(FONT / "StudioIcons.ttf")
    return len(cmap)


def _glyph_table(manifest: dict[str, Any]) -> str:
    """Writes the C# constants that name each glyph.

    Args:
        manifest: The parsed `icons.json`.

    Returns:
        The text of `StudioIcons.g.cs`.
    """
    lines = [
        (
            "// <auto-generated/> scripts/build_icon_font.py writes this file"
            " from assets/icons/icons.json."
        ),
        "",
        f"namespace {NAMESPACE};",
        "",
        (
            f"/// <summary>The glyphs of the {manifest['family']} font by name;"
            " a FontIcon draws them with StudioIconsFontFamily.</summary>"
        ),
        "public static class StudioIcons",
        "{",
    ]
    for index, icon in enumerate(manifest["icons"]):
        if index:
            lines.append("")
        lines.append(f"    /// <summary>{icon['use']}.</summary>")
        lines.append(
            f"    public const string {icon['name']} ="
            f' "\\u{icon["codepoint"]}";'
        )
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Builds the font and the glyph table from `assets/icons/icons.json`."""
    manifest: dict[str, Any] = json.loads(
        (ICONS / "icons.json").read_text(encoding="utf-8")
    )
    glyphs = _build_font(manifest)
    TABLE.mkdir(parents=True, exist_ok=True)
    (TABLE / "StudioIcons.g.cs").write_text(
        _glyph_table(manifest), encoding="utf-8"
    )
    print(f"{(FONT / 'StudioIcons.ttf').relative_to(ROOT)}: {glyphs} glyphs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
